fn python_title(text: &str) -> String {
    let mut previous = false;
    text.chars()
        .map(|c| {
            let value = if previous {
                c.to_lowercase().collect::<String>()
            } else {
                c.to_uppercase().collect::<String>()
            };
            previous = c.is_lowercase() || c.is_uppercase();
            value
        })
        .collect()
}
