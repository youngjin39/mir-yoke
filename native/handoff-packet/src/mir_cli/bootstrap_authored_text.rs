pub const PROFILE_CHOICES: [&str; 4] = [
    "code_app",
    "hybrid_pipeline",
    "infra_runtime",
    "content_workspace",
];
pub(super) fn code_paths(profile: &str) -> Result<Vec<&'static str>, Error> {
    Ok(match profile {
        "code_app" => vec!["app/", "apps/", "packages/"],
        "hybrid_pipeline" => vec!["app/", "apps/", "packages/", "pipelines/"],
        "infra_runtime" => vec!["infra/", "scripts/"],
        "content_workspace" => vec!["content/", "docs/"],
        _ => {
            return Err(Error::new(
                "KeyError",
                crate::executor_execute::repr(profile),
            ));
        }
    })
}
pub fn memory_config_text(
    slug: &str,
    profile: &str,
    onboarding: Option<&serde_json::Value>,
) -> Result<String, Error> {
    let header = concat!(
        "# Active portable memory baseline. Managed by `mir bootstrap` when absent.\n\n",
        "[memory]\nenabled = true\nrequired = true\nbackend = \"sqlite_fts5\"\n",
        "db_path = \".mir/memory.db\"\nvector_mode = \"off\"\nplugin_mode = \"disabled\"\n",
        "recall_policy = \"progressive\"\n\n[memory.embedding]\n",
        "enabled = false\nrequired = false\n",
    );
    if profile == "content_workspace" {
        let onboarding = onboarding.ok_or_else(|| Error::new("AssertionError", ""))?;
        let globs = json_spaces(&json!(super::content_archive_globs(onboarding)));
        return Ok(header.to_owned()
            + &format!(
                concat!(
                    "\n\n[[memory.external_archives]]\nslug = \"{slug}-content\"\nroot = \".\"\n",
                    "mode = \"indexed\"\nglob_include = {globs}\n",
                    "glob_exclude = [\"docs/_archive/**\"]\n",
                ),
                slug = slug,
                globs = globs
            ));
    }
    Ok(header.to_owned()
        + &format!(
            concat!(
                "\n\n[[memory.external_archives]]\nslug = \"{slug}-docs\"\nroot = \"docs\"\n",
                "mode = \"indexed\"\nglob_include = [\"**/*.md\"]\n",
                "glob_exclude = [\"_archive/**\"]\n",
                "\n[[memory.external_archives]]\nslug = \"{slug}-tasks\"\nroot = \"tasks\"\n",
                "mode = \"indexed\"\nglob_include = [\"**/*.md\"]\n",
                "\n[[memory.external_archives]]\nslug = \"{slug}-rules\"\nroot = \".ai-harness\"\n",
                "mode = \"indexed\"\nglob_include = [\"**/*.md\"]\n",
            ),
            slug = slug
        ))
}
